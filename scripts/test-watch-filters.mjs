import assert from 'node:assert/strict';
import fs from 'node:fs';
import {emptyWatch,readWatch,matchingParagraphs,filterChanges} from '../lib/watch-filters.mjs';
const row={id:'a',sha256:'h'};
const index={documents:{a:[{hash:'h',paragraph:1,topic:'Skola',places:['Torup'],docket:'2025 KS0184'},{hash:'h',paragraph:2,topic:'Kultur',places:['Unnaryd'],docket:'2025 KS01840'}]}};
const w={topic:'Skola',place:'Torup',docket:'2025ks0184'};
assert.deepEqual(readWatch(JSON.stringify(w)),w);
assert.deepEqual(readWatch(null),emptyWatch);
assert.throws(()=>readWatch('{}'));
assert.equal(matchingParagraphs(row,w,index).length,1);
assert.equal(matchingParagraphs(row,{...w,place:'Unnaryd'},index).length,0);
assert.equal(matchingParagraphs({...row,sha256:'old'},w,index).length,0);
assert.equal(matchingParagraphs(row,w,null).length,0);
assert.equal(matchingParagraphs(row,w,index,2).length,0);
const diff={added:[row],changed:[],reviews:[{finalDecision:{documentId:'a',sha256:'h',paragraph:1}}]};
assert.equal(filterChanges(diff,w,index).reviews.length,1);
assert.equal(filterChanges(diff,emptyWatch,null),diff);
const real=JSON.parse(fs.readFileSync('public/data/change-watch-index.json','utf8'));
const source=JSON.parse(fs.readFileSync('public/data/protocol-insights.json','utf8'));
assert.equal(Object.values(real.documents).flat().length,source.paragraphs.length);
for(const p of source.paragraphs)assert.ok(real.documents[p.documentId].some(r=>r.paragraph===p.paragraph&&r.page===p.page&&r.hash===p.sourceSha256&&r.docket===(p.docket||'')));
for(const path of ['app/party-timeline.tsx','app/proposal-ledger.tsx','app/api/export/[kind]/route.ts','app/since-last-visit.tsx'])assert.ok(fs.readFileSync(path,'utf8').includes('@/lib/motion-register'));
const legacy=JSON.parse(fs.readFileSync('data/proposal-ledger.json','utf8')).motions;
const additions=JSON.parse(fs.readFileSync('data/reviewed-motion-additions.json','utf8')).motions;
assert.equal(new Set([...legacy,...additions].map(m=>m.id)).size,legacy.length+additions.length);
console.log('PASS: exact docket, same-paragraph AND, hashes, missing coverage, local filter serialization, shared register consumers, index parity');
